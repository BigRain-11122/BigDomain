"""R2181: fold the battery and matrix results into the round record.

The closeout was written while the detached battery was still running,
so the state log line and the export said "launched, reported next
round". Both finished green inside the same window, so the claim is
upgraded to the measured numbers rather than left as a promise.
"""

import io
import json
import os

BASE = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

OLD_LOG = (
    "the full battery and suite-matrix regeneration that R2180 deferred "
    "were launched against this final tree (qa/reconcile-all-R2181.log, "
    "launcher PID in logs/battery-R2181.out) and their outcome is "
    "reported honestly in the next round's first line rather than "
    "claimed here."
)

NEW_LOG = (
    "the full battery and suite-matrix regeneration that R2180 deferred "
    "both closed on this final tree: RUNNER PASS 379/379 suites plus "
    "reconcile controls 7/7 in 695.2s (qa/reconcile-all-R2181.log, "
    "launched detached so the evidence log kept a single utf-8 LF "
    "writer), then the matrix regenerated from that evidence and "
    "--check byte-identical at 379 suites / 3154 criteria "
    "(docs/sandbox-suite-matrix.md, 36640 bytes)."
)

OLD_BACKLOG = "电池与矩阵重生成已对最终树启动（qa/reconcile-all-R2181.log）结果下轮首行如实报。"
NEW_BACKLOG = (
    "电池 RUNNER PASS 379/379 suites + controls 7/7 695.2s"
    "（qa/reconcile-all-R2181.log）·矩阵按该证据重生成后 --check 逐字节同一"
    "（379 suites/3154 criteria·docs/sandbox-suite-matrix.md 36640B）。")

OLD_RESULT = (
    "The R2180 deferred battery and suite-matrix regeneration were "
    "launched against the final tree and are reported next round rather "
    "than claimed here.")
NEW_RESULT = (
    "The R2180 deferred battery and suite-matrix regeneration closed "
    "green on this tree: RUNNER PASS 379/379 suites plus controls 7/7 in "
    "695.2s, matrix regenerated then --check byte-identical at 379 "
    "suites / 3154 criteria.")

OLD_NEXT = (
    "R2182: read the R2181 battery and suite-matrix regeneration result "
    "line by line, then take the next explore seed (R2178 4/10, "
    "api_category_supply_months) - ETA 2026-10-29, within 48h")
NEW_NEXT = (
    "R2182: take the next explore seed (R2178 4/10, "
    "api_category_supply_months - the category supply trend that "
    "api_categories only answers as a snapshot) with criteria "
    "pre-registered before code - ETA 2026-10-29, within 48h")


def main():
    spath = os.path.join(BASE, "src", "os", "state.json")
    state = json.loads(open(spath, "rb").read().decode("utf-8"))
    hits = 0
    for i, line in enumerate(state["log"]):
        if OLD_LOG in line:
            state["log"][i] = line.replace(OLD_LOG, NEW_LOG)
            hits += 1
    assert hits == 1, "log upgrade anchor not unique (%d)" % hits
    with io.open(spath, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(state, ensure_ascii=False, indent=2))
        handle.write("\n")

    bpath = os.path.join(BASE, "src", "os", "backlog.md")
    btext = io.open(bpath, encoding="utf-8").read()
    assert btext.count(OLD_BACKLOG) == 1, "backlog anchor missing"
    btext = btext.replace(OLD_BACKLOG, NEW_BACKLOG)
    io.open(bpath, "w", encoding="utf-8", newline="\n").write(btext)

    epath = os.path.join(BASE, "docs", "status-export.json")
    export = json.loads(open(epath, "rb").read().decode("utf-8"))
    export["results"][-1][1] = export["results"][-1][1].replace(
        OLD_RESULT, NEW_RESULT)
    assert OLD_RESULT not in export["results"][-1][1]
    export["ceo_face"]["next_milestone"] = NEW_NEXT
    export["ceo_face"]["current"] = export["ceo_face"]["current"].replace(
        "the deferred full battery and matrix regeneration were launched "
        "on this tree",
        "the deferred full battery closed green (379/379 suites) and the "
        "matrix regenerated byte-identically")
    with io.open(epath, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(export, ensure_ascii=False, indent=2))
        handle.write("\n")
    print("battery and matrix results folded into state, backlog, export")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())